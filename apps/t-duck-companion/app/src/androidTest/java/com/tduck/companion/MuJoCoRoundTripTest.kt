package com.tduck.companion

import android.graphics.Bitmap
import android.util.Base64
import android.util.Log
import androidx.compose.ui.test.*
import androidx.compose.ui.test.junit4.createAndroidComposeRule
import androidx.lifecycle.ViewModelProvider
import androidx.test.espresso.Espresso.closeSoftKeyboard
import androidx.test.platform.app.InstrumentationRegistry
import java.io.ByteArrayOutputStream
import java.security.KeyStore
import java.security.cert.CertificateFactory
import java.util.concurrent.CopyOnWriteArrayList
import javax.net.ssl.HttpsURLConnection
import javax.net.ssl.SSLContext
import javax.net.ssl.SSLSocketFactory
import javax.net.ssl.TrustManagerFactory
import kotlinx.coroutines.*
import kotlinx.coroutines.flow.collect
import org.json.JSONObject
import org.junit.*
import org.junit.Assert.*

/** Actual UI -> HTTPS -> pinned MuJoCo/ONNX/BAM -> UI. No fake transport or telemetry injection. */
class MuJoCoRoundTripTest {
 @get:Rule val compose = createAndroidComposeRule<MainActivity>()
 private lateinit var model: CompanionModel
 private lateinit var originalFactory: SSLSocketFactory
 private lateinit var config: JSONObject
 private val observed = CopyOnWriteArrayList<RobotUi>()
 private val scope = CoroutineScope(SupervisorJob() + Dispatchers.Main.immediate)

 @Before fun prepare() {
  val context = InstrumentationRegistry.getInstrumentation().context
  Assume.assumeTrue("TC-02 bridge fixture must be generated by integration workflow", context.assets.list("")!!.contains("tc02-bridge.json"))
  config = JSONObject(context.assets.open("tc02-bridge.json").bufferedReader().use { it.readText() })
  originalFactory = HttpsURLConnection.getDefaultSSLSocketFactory()
  val ca = context.assets.open("tc02-ca.pem").use { CertificateFactory.getInstance("X.509").generateCertificate(it) }
  val store = KeyStore.getInstance(KeyStore.getDefaultType()).apply { load(null, null); setCertificateEntry("ephemeral-test-ca", ca) }
  val trust = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm()).apply { init(store) }
  val ssl = SSLContext.getInstance("TLS").apply { init(null, trust.trustManagers, null) }
  // Test-only CA trust; certificate chain and hostname validation remain enabled in production transport.
  HttpsURLConnection.setDefaultSSLSocketFactory(ssl.socketFactory)
  compose.runOnIdle {
   model = ViewModelProvider(compose.activity)[CompanionModel::class.java]
   model.connectDemo()
   scope.launch(start = CoroutineStart.UNDISPATCHED) { model.state.collect { observed.add(it) } }
  }
 }
 @After fun cleanup() {
  if(::model.isInitialized) compose.runOnIdle { model.disconnect() }
  scope.cancel()
  if(::originalFactory.isInitialized) HttpsURLConnection.setDefaultSSLSocketFactory(originalFactory)
 }
 private fun clickCommand(command: String) { compose.onNodeWithTag("command-$command").performScrollTo().assertIsEnabled().performClick() }
 private fun waitAck(command: String) { compose.waitUntil(10_000) { model.state.value.lastAckCommand == command } }

 @Test fun androidControlChangesActualMuJoCoAndTelemetryIsVisible() {
  compose.onNodeWithTag("tab-Settings").performClick()
  compose.onNodeWithTag("bridge-url").performScrollTo().performTextInput(config.getString("endpoint"))
  compose.onNodeWithTag("bridge-token").performScrollTo().performTextInput(config.getString("token"))
  closeSoftKeyboard()
  compose.onNodeWithTag("bridge-connect").performScrollTo().performClick()
  compose.waitUntil(20_000) { model.state.value.connected && model.state.value.source == "mujoco" }
  compose.runOnIdle {
   assertFalse(model.state.value.batteryAvailable)
   assertFalse(model.state.value.availableSensors.contains("distance"))
   assertEquals(14, model.state.value.pose!!.joints.size)
   assertFalse(model.state.value.capabilities.contains("recover"))
  }
  compose.onNodeWithTag("tab-Control").performClick()
  clickCommand("stand"); waitAck("stand")
  compose.waitUntil(10_000) { (model.state.value.pose?.simulationTimeS ?: 0.0) >= .5 }
  val xBefore = model.state.value.pose!!.positionM[0]
  clickCommand("forward"); waitAck("forward")
  val forwardId = model.state.value.lastAckId
  compose.waitUntil(10_000) {
   observed.any { it.source == "mujoco" && it.lastTelemetryCommandId == forwardId &&
    it.mode == "forward" && (it.pose?.positionM?.get(0) ?: xBefore) > xBefore + .005 }
  }
  // No app Stop sent here: independent bridge watchdog must expire the movement lease.
  compose.waitUntil(10_000) { model.state.value.mode == "stop" && model.state.value.warnings.any { it.contains("lease expired") } }
  val afterForward = model.state.value
  assertTrue("Actual forward displacement too small", afterForward.pose!!.positionM[0] - xBefore > .015)
  compose.onNodeWithText("■  EMERGENCY STOP").performClick(); waitAck("stop")
  val stopId = model.state.value.lastAckId
  compose.waitUntil(10_000) { model.state.value.lastTelemetryCommandId == stopId && model.state.value.mode == "stop" }
  val yawBeforeLeft = model.state.value.yaw
  clickCommand("left"); waitAck("left")
  compose.waitUntil(10_000) { model.state.value.mode == "stop" && model.state.value.yaw > yawBeforeLeft + 2.0 }
  val yawAfterLeft = model.state.value.yaw
  clickCommand("right"); waitAck("right")
  compose.waitUntil(10_000) { model.state.value.mode == "stop" && model.state.value.yaw < yawAfterLeft - 2.0 }
  clickCommand("rest"); waitAck("rest")
  compose.waitUntil(10_000) { model.state.value.motionState == "paused" && model.state.value.mode == "rest" }
  val visible = model.state.value
  assertEquals("ready", visible.status)
  compose.onNodeWithTag("tab-Sensors").performClick()
  compose.onNodeWithTag("sensor-position-x").performScrollTo().assertIsDisplayed()
   .assertTextEquals("%.3f m".format(visible.pose!!.positionM[0]))
  compose.onNodeWithTag("sensor-simulation-time").performScrollTo().assertIsDisplayed()
   .assertTextEquals("%.2f s".format(visible.pose.simulationTimeS))
  val report = JSONObject().put("verified", true).put("telemetry_source", visible.source)
   .put("forward_command_id", forwardId).put("stop_command_id", stopId)
   .put("x_before_m", xBefore).put("x_after_forward_m", afterForward.pose.positionM[0])
   .put("forward_displacement_m", afterForward.pose.positionM[0] - xBefore)
   .put("visible_x_m", visible.pose.positionM[0]).put("visible_frame_id", visible.pose.frameId)
   .put("visible_simulation_time_s", visible.pose.simulationTimeS).put("joints", visible.pose.joints.size)
   .put("watchdog_observed", true).put("orientation_roll_deg", visible.roll).put("orientation_pitch_deg", visible.pitch)
   .put("left_contact", visible.leftContact).put("right_contact", visible.rightContact)
   .put("left_turn_delta_deg", yawAfterLeft - yawBeforeLeft).put("battery_available", visible.batteryAvailable)
   .put("ui_position_asserted", true).put("ui_time_asserted", true)
  Log.i("TC02_RESULT", report.toString())
  val screenshot = checkNotNull(InstrumentationRegistry.getInstrumentation().uiAutomation.takeScreenshot())
  val bytes = ByteArrayOutputStream(); screenshot.compress(Bitmap.CompressFormat.PNG, 100, bytes); screenshot.recycle()
  val chunks = Base64.encodeToString(bytes.toByteArray(), Base64.NO_WRAP).chunked(1200)
  chunks.forEachIndexed { index, chunk -> Log.i("TC02_SCREEN", "$index/${chunks.size} $chunk") }
 }
}
